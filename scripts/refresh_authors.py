#!/usr/bin/env python3
"""Regenerate data/authors.yaml from the GitHub profiles of every author
referenced in content/posts/.

Collects the unique logins from each post's `authors` frontmatter, fetches each
profile from the GitHub API, and writes the result to data/authors.yaml. On a
fetch failure the existing entry (if any) is preserved, so a transient API
hiccup never wipes an author. Run by the "Refresh author profiles" workflow,
which opens a PR with whatever changed; the site build itself never calls the
API.

Auth: set GITHUB_TOKEN to raise the rate limit (the workflow passes the Action's
token automatically). Works unauthenticated too, within the 60-req/hour limit.
"""

from __future__ import annotations

import json
import os
import sys
import urllib.error
import urllib.request
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
POSTS_DIR = REPO_ROOT / "content" / "posts"
DATA_FILE = REPO_ROOT / "data" / "authors.yaml"

HEADER = (
    "# GitHub author profiles, baked in so the site builds offline (no API token at\n"
    "# build time). DO NOT edit by hand — regenerated by scripts/refresh_authors.py\n"
    "# via the \"Refresh author profiles\" workflow, which opens a PR with any changes.\n"
    "# Keyed by GitHub login exactly as written in a post's `authors` frontmatter.\n"
)


def collect_logins() -> list[str]:
    """Unique author logins across every post's frontmatter, in sorted order."""
    logins: set[str] = set()
    for index in POSTS_DIR.rglob("index.md"):
        front = parse_frontmatter(index)
        for login in front.get("authors", []) or []:
            if isinstance(login, str) and login.strip():
                logins.add(login.strip())
    return sorted(logins)


def parse_frontmatter(path: Path) -> dict:
    """Return the YAML frontmatter of a Markdown file (the block between the
    leading `---` fences), or an empty dict if there isn't one."""
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---"):
        return {}
    parts = text.split("---", 2)
    if len(parts) < 3:
        return {}
    try:
        return yaml.safe_load(parts[1]) or {}
    except yaml.YAMLError as exc:
        print(f"warn: could not parse frontmatter in {path}: {exc}", file=sys.stderr)
        return {}


def fetch_profile(login: str, token: str | None) -> dict | None:
    """Fetch one GitHub profile; return the author dict or None on failure."""
    req = urllib.request.Request(f"https://api.github.com/users/{login}")
    req.add_header("Accept", "application/vnd.github+json")
    req.add_header("User-Agent", "latent-blog-refresh-authors")
    if token:
        req.add_header("Authorization", f"Bearer {token}")
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            user = json.load(resp)
    except (urllib.error.URLError, TimeoutError, json.JSONDecodeError) as exc:
        print(f"warn: fetch failed for {login!r}: {exc}", file=sys.stderr)
        return None
    return {
        "name": user.get("name") or login,
        "avatar": user.get("avatar_url") or "",
        "bio": (user.get("bio") or "").strip(),
        "url": user.get("html_url") or f"https://github.com/{login}",
    }


def load_existing() -> dict:
    if not DATA_FILE.exists():
        return {}
    return yaml.safe_load(DATA_FILE.read_text(encoding="utf-8")) or {}


def main() -> int:
    token = os.environ.get("GITHUB_TOKEN")
    logins = collect_logins()
    if not logins:
        print("No authors referenced in content/posts/; nothing to do.")
        return 0

    existing = load_existing()
    authors: dict[str, dict] = {}
    failures = 0
    for login in logins:
        profile = fetch_profile(login, token)
        if profile is None:
            if login in existing:
                print(f"  {login}: keeping existing entry (fetch failed)")
                authors[login] = existing[login]
            else:
                failures += 1
            continue
        authors[login] = profile
        print(f"  {login}: {profile['name']}")

    DATA_FILE.parent.mkdir(exist_ok=True)
    with DATA_FILE.open("w", encoding="utf-8") as fh:
        fh.write(HEADER)
        yaml.safe_dump(
            authors, fh, sort_keys=True, allow_unicode=True, default_flow_style=False
        )
    print(f"Wrote {len(authors)} author(s) to {DATA_FILE.relative_to(REPO_ROOT)}.")

    # Fail only if a brand-new author couldn't be fetched at all — an empty entry
    # would otherwise ship a broken byline.
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
